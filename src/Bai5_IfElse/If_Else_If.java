package Bai5_IfElse;

public class If_Else_If {
    public static void main(String[] args) {
        int mark = 65;
        if (mark < 50){
            System.out.println("Tạch");

        }else if (mark >= 50 && mark < 60){
            System.out.println("Xếp loại D");
        } else if (mark >= 60) {
            System.out.println("Đỗ");

        }
    }
}
