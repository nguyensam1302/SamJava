package Bai6_VongLap_For;

public class While {
    public static void main(String[] args) {
        int i = 0;
        while (i < 10){
            System.out.println(i);
            i += 1;
        }
        int a = 10;
        do {
            System.out.println(i);
            a += 1;
        }
        while (a < 10);
    }
}
